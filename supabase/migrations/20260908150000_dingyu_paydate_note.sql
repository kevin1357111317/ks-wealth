--
-- 原本繳款日是每月 1 日，那時候每個邊界都剛好對齊：
--   寬限期 = 第 1~36 期，最後一期 2027-03-01 = 寬限期間結束
--   全期   = 第 1~360 期，最後一期 2054-03-01 = 借款期間結束
--   => 攤還 324 期，年金算出來就是 97,207.69，跟攤還表上 97,208/97,207 交替吻合。
-- 反推出來的「324 期」不是湊出來的，那就是銀行原始的合約。
--
-- 改成每月 5 日之後切換點順延一期（寬限期變成到第 37 期），324 期攤還跟著排到
-- 第 361 期 2054-04-05。多出來的 35 天是改期造成的，不是資料錯誤。
--
-- 寬限期本金不動、利息又是 ÷12 跟天數無關，所以早期那幾期的 due_date 記成 5 日
-- 而不是 1 日，不影響任何算出來的數字。

